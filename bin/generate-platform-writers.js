const fs = require('fs');
const path = require('path');

const PACKAGE_ROOT = path.resolve(__dirname, '..');
const registryPath = path.join(PACKAGE_ROOT, 'skill-registry.json');
const platformWritersDir = path.join(PACKAGE_ROOT, 'skills/platform-writers');

const GENERATED_NOTICE = '<!-- This file is generated by bin/generate-platform-writers.js. Do not edit by hand. -->';
const GENERATED_NAME_PREFIX = 'writer-platform-';

function templateTypeForAdapter(adapter) {
  switch (adapter) {
    case 'adapter-community-discussion':
      return 'discussion';
    case 'adapter-launch':
      return 'launch';
    case 'adapter-showcase':
      return 'showcase';
    case 'adapter-social-shortform':
      return 'shortform';
    case 'adapter-technical-blog':
    default:
      return 'article';
  }
}

function stylePathForAdapter(adapter) {
  switch (adapter) {
    case 'adapter-community-discussion':
      return 'knowledge/styles/community-post.md';
    case 'adapter-launch':
      return 'knowledge/styles/launch-post.md';
    case 'adapter-social-shortform':
      return 'knowledge/styles/build-in-public.md';
    case 'adapter-showcase':
      return 'knowledge/styles/build-in-public.md';
    case 'adapter-technical-blog':
    default:
      return 'knowledge/styles/technical-blog.md';
  }
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function writeJson(filePath, value) {
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

function readPlatformTitle(platformPath, fallback) {
  const absolutePath = path.join(PACKAGE_ROOT, platformPath);
  const content = fs.readFileSync(absolutePath, 'utf8');
  const titleMatch = content.match(/^#\s+(.+)$/m);
  return titleMatch ? titleMatch[1].trim() : fallback;
}

function titleCaseSlug(slug) {
  return slug
    .split('-')
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

function skillMarkdown(platform, title) {
  const skillName = `${GENERATED_NAME_PREFIX}${platform.slug}`;
  const categoryList = platform.categories.join(', ');
  const adapterPath = `skills/${platform.recommended_adapter}/SKILL.md`;
  const stylePath = stylePathForAdapter(platform.recommended_adapter);
  const baseTemplatePath = `templates/base/${templateTypeForAdapter(platform.recommended_adapter)}.md`;
  const platformTemplatePath = `templates/platforms/${platform.slug}/`;

  return `${GENERATED_NOTICE}
---
name: ${skillName}
description: Write platform-specific drafts for ${title} using its dedicated language, length, tone, format, and community rules.
---

# ${title} Writer

Use this skill when the target platform is \`${platform.slug}\` / ${title}. This is the platform-specific writing capability for that website, not a generic adapter.

## Knowledge To Load

- \`${platform.path}\`
- \`${adapterPath}\`
- \`${stylePath}\`
- \`${baseTemplatePath}\`
- \`${platformTemplatePath}\` when a platform override template exists
- \`knowledge/rules/anti-spam.md\`
- \`knowledge/rules/no-auto-publish.md\`
- \`knowledge/rules/disclosure.md\`
- \`knowledge/rules/factual-accuracy.md\`

## Inputs

- Project brief matching \`schemas/project-brief.schema.json\`, or a base draft matching \`schemas/platform-draft.schema.json\`.
- Any user-provided assets, links, screenshots, metrics, code snippets, or launch details.

## Platform Binding

- Platform slug: \`${platform.slug}\`
- Recommended adapter: \`${platform.recommended_adapter}\`
- Primary language code: \`${platform.primary_language}\`
- Categories: ${categoryList}
- Target audience: ${platform.target_audience}

## Writing Contract

1. Load \`${platform.path}\` first and treat it as the source of truth for this website.
2. Extract the site's required language, regional spelling, expected length, tone, accepted content shapes, formatting conventions, required assets, and banned patterns.
3. Use \`${platform.recommended_adapter}\` only as a helper pattern. If the generic adapter conflicts with \`${platform.slug}\`, the platform profile wins.
4. Match the site's expected content length. Short-post platforms must stay short; long-form editorial or tutorial platforms must provide enough depth, evidence, and structure.
5. Match the site's voice. Preserve literary, technical, formal, skeptical, educational, founder-led, visual, or community-native tone when the profile asks for it.
6. Use only facts from the brief, base draft, loaded knowledge, templates, and user-provided materials. Do not invent URLs, metrics, version numbers, names, screenshots, testimonials, or claims.
7. Include required placeholders only when a platform field is mandatory but the fact is missing, and set \`status\` to \`needs_review\`.
8. Remove content types listed as poor fit for this platform. If the project is fundamentally unsuitable, return a \`needs_review\` draft explaining the fit problem instead of forcing a post.
9. Do not publish or imply that publication has happened.

## Output

Return a draft matching \`schemas/platform-draft.schema.json\`:

- \`platform\`: \`${platform.slug}\`
- \`status\`: \`draft\` or \`needs_review\`
- \`metadata.recommended_adapter\`: \`${platform.recommended_adapter}\`
- \`metadata.platform_constraints_applied\`: checklist covering language, length, tone, structure, formatting, evidence, and anti-spam constraints
`;
}

function generatedSkillEntry(platform) {
  const baseTemplatePath = `templates/base/${templateTypeForAdapter(platform.recommended_adapter)}.md`;
  const platformTemplatePath = `templates/platforms/${platform.slug}/`;
  const knowledge = [
    platform.path,
    `skills/${platform.recommended_adapter}/SKILL.md`,
    stylePathForAdapter(platform.recommended_adapter),
    baseTemplatePath
  ];

  if (fs.existsSync(path.join(PACKAGE_ROOT, platformTemplatePath))) {
    knowledge.push(platformTemplatePath);
  }

  knowledge.push(
    'knowledge/rules/anti-spam.md',
    'knowledge/rules/no-auto-publish.md',
    'knowledge/rules/disclosure.md',
    'knowledge/rules/factual-accuracy.md'
  );

  return {
    name: `${GENERATED_NAME_PREFIX}${platform.slug}`,
    path: `skills/platform-writers/${platform.slug}/SKILL.md`,
    input_schema: 'schemas/project-brief.schema.json',
    output_schema: 'schemas/platform-draft.schema.json',
    knowledge
  };
}

function main() {
  const registry = readJson(registryPath);
  const platforms = registry.platform_knowledge || [];

  fs.mkdirSync(platformWritersDir, { recursive: true });

  for (const platform of platforms) {
    const title = readPlatformTitle(platform.path, titleCaseSlug(platform.slug));
    const skillDir = path.join(platformWritersDir, platform.slug);
    fs.mkdirSync(skillDir, { recursive: true });
    fs.writeFileSync(path.join(skillDir, 'SKILL.md'), skillMarkdown(platform, title), 'utf8');
  }

  const nonGeneratedSkills = registry.skills.filter(skill => !skill.name.startsWith(GENERATED_NAME_PREFIX));
  registry.skills = nonGeneratedSkills.concat(platforms.map(generatedSkillEntry));

  writeJson(registryPath, registry);

  console.log(`Generated ${platforms.length} platform writer skills in ${path.relative(PACKAGE_ROOT, platformWritersDir)}`);
  console.log(`Updated ${path.relative(PACKAGE_ROOT, registryPath)} with ${platforms.length} generated skill entries`);
}

main();
